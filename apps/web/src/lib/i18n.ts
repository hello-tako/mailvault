const DICTS: Record<Lang, Dict> = { en, vi };

export function detectLang(browserLanguage: string, stored: string | null): Lang {
  if (stored === "en" || stored === "vi") return stored;
  return String(browserLanguage).toLowerCase().startsWith("vi") ? "vi" : "en";
}

function readStored(): string | null {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

let current: Lang = detectLang(
  typeof navigator !== "undefined" ? navigator.language : "en",
  readStored(),
);
const listeners = new Set<() => void>();

if (typeof document !== "undefined") document.documentElement.lang = current;

export function lang(): Lang {
  return current;
}

export function setLang(next: Lang): void {
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* private mode: the choice just won't survive a reload */
  }
  if (typeof document !== "undefined") document.documentElement.lang = next;
  tellServiceWorker(next);
  for (const fn of listeners) fn();
}

/**
 * The service worker has no access to localStorage, so it cannot look the choice up
 * itself. It is told on every change and on startup; until it hears, it uses the browser
 * language — which is exactly what the app itself would have chosen.
 */
export function tellServiceWorker(next: Lang): void {
  try {
    navigator.serviceWorker?.controller?.postMessage({ type: "mailvault-lang", value: next });
  } catch {
    /* no worker registered yet */
  }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

/** Re-renders the tree when the language changes; every string is read through `t()`. */
export function useLang(): Lang {
  const [, force] = useState(0);
  useEffect(() => {
    const bump = () => force((n) => n + 1);
    listeners.add(bump);
    return () => {
      listeners.delete(bump);
    };
  }, []);
  return current;
}

export function languageName(l: Lang): string {
  return l === "vi" ? "Tiếng Việt" : "English";
}

/** Phrases for the one validator that runs live in the form, so the reason is in the UI language. */
export function localPartPhrases(): LocalPartPhrases {
  return {
    empty: t("lp.empty"),
    tooLong: (max, n) => t("lp.tooLong", { max, n }),
    badChar: (c) => t("lp.badChar", { c }),
    doubleDot: t("lp.doubleDot"),
    startsWith: t("lp.startsWith"),
    endsWith: t("lp.endsWith"),
    reserved: (v) => t("lp.reserved", { v }),
  };
}

/** The same, for the sentence that describes a rule. */
export function rulePhrases(): RulePhrases {
  return {
    from: (domain) => t("rule.phFrom", { domain }),
    subjectContains: (s) => t("rule.phSubject", { s }),
    inDomain: t("rule.phDomain"),
    onAlias: t("rule.phAlias"),
    withCode: t("rule.phWithCode"),
    withoutCode: t("rule.phNoCode"),
    withAttachment: t("rule.phWithAtt"),
    withoutAttachment: t("rule.phNoAtt"),
    archived: t("rule.phArchived"),
    tagged: (tag) => t("rule.phTagged", { t: tag }),
    join: t("rule.phJoin"),
    byRule: t("rule.phBy"),
    everything: t("rule.phAll"),
  };
}
